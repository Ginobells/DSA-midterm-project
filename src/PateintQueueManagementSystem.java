    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
  String id = txtPatientID.getText().trim();
    String name = txtPatientName.getText().trim();
    String ageText = txtAge.getText().trim();
    String reason = txtReason.getText().trim();

    if (id.isEmpty() || name.isEmpty()
            || ageText.isEmpty() || reason.isEmpty()) {

        JOptionPane.showMessageDialog(this,
                "Please fill in all fields!");
        return;
    }

    try {

        int age = Integer.parseInt(ageText);

        if (age <= 0) {
            JOptionPane.showMessageDialog(this,
                    "Please enter a valid age!");
            return;
        }

        Patient patient = new Patient(id, name, age, reason);

        if (ClinicQueue.registerPatient(patient)) {

            JOptionPane.showMessageDialog(this,
                    "Patient registered successfully!");

            txtPatientID.setText("");
            txtPatientName.setText("");
            txtAge.setText("");
            txtReason.setText("");

            displayWaitingPatients();

        } else {

            JOptionPane.showMessageDialog(this,
                    "Patient ID already exists!");
        }

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(this,
                "Age must contain numbers only!");
    }


    }//GEN-LAST:event_jButton2ActionPerformed

